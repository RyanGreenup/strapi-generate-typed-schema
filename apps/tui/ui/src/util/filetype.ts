/** Infers parser names from extensions, maps JavaScript and JSX to TypeScript, and defaults to `none`. */
export function filetype(input?: string): string {
  if (input === undefined || input === "") return "none";
  const language = LANGUAGE_EXTENSIONS[path.extname(input)];
  if (
    language !== undefined &&
    ["typescriptreact", "javascriptreact", "javascript"].includes(language)
  ) {
    return "typescript";
  }
  return language ?? "none";
}
