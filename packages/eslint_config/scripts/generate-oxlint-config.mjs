import { spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const intermediateFilename = '.oxlintrc.generated.json'
const intermediateFile = resolve(packageDir, intermediateFilename)
const outputFile = resolve(packageDir, 'src/generated/oxlint-solid.js')

rmSync(intermediateFile, { force: true })
const migrate = spawnSync(
  process.execPath,
  [
    'node_modules/@oxlint/migrate/dist/bin/oxlint-migrate.mjs',
    'src/configs/oxlint.js',
    '--output-file',
    intermediateFilename,
    '--type-aware',
    '--js-plugins',
  ],
  { cwd: packageDir, stdio: 'inherit' },
)

if (migrate.status !== 0) {
  rmSync(intermediateFile, { force: true })
  process.exit(migrate.status ?? 1)
}

/** @type {{ $schema?: string, rules?: Record<string, unknown>, overrides?: { rules?: Record<string, unknown> }[] }} */
const config = JSON.parse(readFileSync(intermediateFile, 'utf8'))
delete config.$schema
for (const rules of [
  config.rules,
  ...(config.overrides ?? []).map(override => override.rules),
]) {
  const style = rules?.['import/consistent-type-specifier-style']
  if (Array.isArray(style) && style[1] === 'top-level')
    style[1] = 'prefer-top-level'
}

const banner = `// Generated by pnpm generate:oxlint. Do not edit directly.\n/** @type {import('oxlint').OxlintConfig} */\n`
mkdirSync(dirname(outputFile), { recursive: true })
writeFileSync(
  outputFile,
  `${banner}export default ${JSON.stringify(config, null, 2)}\n`,
)
rmSync(intermediateFile, { force: true })
